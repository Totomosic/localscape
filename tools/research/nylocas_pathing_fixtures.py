#!/usr/bin/env python3
"""Export checksum-verified Blert contexts for the real Kotlin movement harness.

Run from the workspace root. The harness predicts one step conditional on the
recorded focal position and surrounding NPC snapshots; it is not a full raid
reconstruction. Before/after blockers test two timing assumptions, not bounds
on every possible interleaving of server actors.
"""
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'docs/nylo-pathing'))
from analyze import checked, face, fingerprint, pos


def main():
    old = ROOT / 'docs/research/nylocas'
    new = ROOT / 'docs/nylo-pathing'
    provenance=json.loads((new/'manifest.json').read_text())
    for label in ('classification','previousCorpus'):
        spec=provenance[label]
        assert hashlib.sha256((new/spec['path']).read_bytes()).hexdigest()==spec['sha256'],label
    with (old / 'lane-spawn-targets.csv').open() as f:
        assignments = {(int(r['wave']),r['lane'],r['initial_style'],r['big']=='True',
                        int(r['spawn_x']),int(r['spawn_y'])):r for r in csv.DictReader(f)}
    special = {
        'eb3793f3-ce4a-4fcf-8ef9-e2098d39914a': [('small-NE',33313,49,61)],
        '1073635f-5326-4bac-a147-8fdf6299f761': [('big-SE',64113,236,259)],
        'a37210fe-5737-480f-8fca-518e56205e9b': [('big-SW',34729,337,352)],
    }
    lines = ['# Generated by tools/research/nylocas_pathing_fixtures.py; see docs/nylo-pathing/manifest.json']
    count = intervals = 0
    for root in (old,new):
        manifest = json.loads((root/'manifest.json').read_text())
        for rec in manifest['recordings']:
            raid = checked(root,rec['files']['raid'])
            events = checked(root,rec['files']['events'])
            assert raid['mode']==11 and raid['scale'] in (1,2)
            npcs = {n['roomId']:n for n in raid['tobRooms']['nylocas']['npcs'].values() if n['type']==2}
            frames = {}
            for e in events:
                if e['type'] in (7,8) and e['npc']['roomId'] in npcs:
                    frames.setdefault(e['tick'],{})[e['npc']['roomId']]=e
            specs = list(special.get(rec['uuid'],[]))
            arrival_names = set()
            for wave in (25,27):
                n = next(n for n in npcs.values() if n['nylo']['wave']==wave and n['nylo']['spawnType']==3 and n['nylo']['big'])
                rid=n['roomId']
                ticks=[t for t,fr in frames.items() if rid in fr and fr[rid]['npc']['hitpoints']>>16>0
                       and 8342<=fr[rid]['npc']['id']<=8347 and 3290<=pos(fr[rid])[0]<=3301
                       and 4243<=pos(fr[rid])[1]<=4254 and t-n['spawnTick']<52]
                if ticks:
                    name=rec['uuid'][:8]+'-'+str(wave)
                    specs.append((name,rid,min(ticks),min(max(ticks),min(ticks)+35)))
                    arrival_names.add(name)
            for name,rid,start,end in specs:
                n=npcs[rid];a=assignments[fingerprint(n)];assert a['aggro']=='False'
                y=n['nylo'];point=n['spawnPoint']
                slot=({'west':'WestNorth' if point['y']==4249 else 'WestSouth',
                       'south':'SouthEast' if point['x']==3296 else 'SouthWest',
                       'east':'EastNorth' if point['y']==4249 else 'EastSouth'})[a['lane']]
                sustained = any(t+1 in frames and rid in frames[t+1]
                                and face(pos(frames[t][rid]),2,'SE')=='N'
                                and pos(frames[t][rid])==pos(frames[t+1][rid])
                                and all(8342<=e['npc']['id']<=8347 and e['npc']['hitpoints']>>16>0
                                        for e in (frames[t][rid],frames[t+1][rid]))
                                for t in range(start,end) if rid in frames.get(t,{}))
                expected='N' if name in arrival_names and sustained else '-'
                lines.append('\t'.join(map(str,['C',name,rec['uuid'],rid,2 if y['big'] else 1,a['target'],slot,expected])))
                count+=1
                def blockers(t):
                    out=[]
                    for other,e in sorted(frames[t].items()):
                        if other==rid:continue
                        size=2 if npcs[other]['nylo']['big'] and 8348<=e['npc']['id']<=8353 else 1
                        out.append(','.join(map(str,[*pos(e),size])))
                    return ';'.join(out) or '-'
                for t in range(start,end):
                    before=frames.get(t,{}).get(rid);after=frames.get(t+1,{}).get(rid)
                    if before is None or after is None:continue
                    if any(e['npc']['hitpoints']>>16<=0 or not 8342<=e['npc']['id']<=8347 for e in (before,after)):continue
                    lines.append('\t'.join(map(str,['T',t,*pos(before),*pos(after),blockers(t),blockers(t+1)])))
                    intervals+=1
    dest=ROOT/'upstream/rsmod/content/areas/dungeons/nylocas/src/integration/resources/nylocas-pathing.tsv'
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text('\n'.join(lines)+'\n')
    print(f'{count} cases, {intervals} transitions -> {dest.relative_to(ROOT)}')


if __name__=='__main__':main()
